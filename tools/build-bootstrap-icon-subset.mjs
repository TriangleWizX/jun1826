import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ICON_DIR = path.join(ROOT, 'src/assets/icons/bootstrap');
const OUTPUT_PATH = path.join(ROOT, 'src/assets/css/bootstrap-icons-local.css');
const PUBLIC_ICON_ROOT = '/assets/icons/bootstrap';

const parseArgs = () => {
  const args = new Set(process.argv.slice(2));
  for (const arg of args) {
    if (arg !== '--check') throw new Error(`Unknown argument: ${arg}`);
  }
  return { check: args.has('--check') };
};

const buildCss = (iconNames) => {
  const rules = iconNames
    .map((name) => `.bi-${name}{--ss-bi-mask:url("${PUBLIC_ICON_ROOT}/${name}.svg")}`)
    .join('\n');

  return `/* Generated by tools/build-bootstrap-icon-subset.mjs. Do not edit directly. */
.bi{
  --ss-bi-mask:none;
  display:inline-block;
  flex:0 0 auto;
  width:1em;
  height:1em;
  vertical-align:-0.125em;
  color:inherit;
  background-color:currentColor;
  -webkit-mask-image:var(--ss-bi-mask);
  mask-image:var(--ss-bi-mask);
  -webkit-mask-position:center;
  mask-position:center;
  -webkit-mask-repeat:no-repeat;
  mask-repeat:no-repeat;
  -webkit-mask-size:100% 100%;
  mask-size:100% 100%;
}
.bi::before{content:none!important;display:none!important}
${rules}
`;
};

const main = async () => {
  const { check } = parseArgs();
  const entries = await fs.readdir(ICON_DIR, { withFileTypes: true });
  const iconNames = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.svg'))
    .map((entry) => entry.name.slice(0, -4))
    .sort();

  if (!iconNames.length) throw new Error(`No SVG icons found in ${ICON_DIR}.`);
  for (const name of iconNames) {
    if (!/^[a-z0-9-]+$/.test(name)) {
      throw new Error(`Unsupported Bootstrap Icon filename: ${name}.svg`);
    }
  }

  const css = buildCss(iconNames);
  if (check) {
    let current = '';
    try {
      current = await fs.readFile(OUTPUT_PATH, 'utf8');
    } catch {
      throw new Error(`Missing generated icon stylesheet: ${path.relative(ROOT, OUTPUT_PATH)}`);
    }
    if (current !== css) {
      throw new Error(
        `${path.relative(ROOT, OUTPUT_PATH)} is stale. Run npm run icons:build.`
      );
    }
    console.log(`Local Bootstrap Icon subset is current (${iconNames.length} SVG mappings).`);
    return;
  }

  await fs.writeFile(OUTPUT_PATH, css, 'utf8');
  console.log(
    `Wrote ${path.relative(ROOT, OUTPUT_PATH)} with ${iconNames.length} SVG mappings.`
  );
};

main().catch((error) => {
  console.error(error.stack || error.message || String(error));
  process.exit(1);
});
