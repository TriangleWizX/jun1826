#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import parser from './lib/css-asset-parser.cjs';

const {
  ROOT,
  assertSafeExistingFile,
  assertSafeOutputPath,
  atomicWriteFile,
  relativeLabel,
  resolveWorkspacePath,
} = parser;

const THIS_FILE = fileURLToPath(import.meta.url);
const BUILD_VERSION = 'bootstrap-site-1';
const BOOTSTRAP_VERSION = '5.3.3';
const DEFAULT_SOURCE = 'assets/scss/bootstrap-site.scss';
const DEFAULT_OUTPUT = 'assets/css/bootstrap-site.css';

const usage = `Usage: node tools/build-bootstrap-site.mjs [--check] [--source=<path>] [--output=<path>]

Compile the pinned selective Bootstrap Sass entrypoint. With --check, compare
the deterministic output without writing it.`;

const parseArgs = (args = process.argv.slice(2)) => {
  let check = false;
  let source = DEFAULT_SOURCE;
  let output = DEFAULT_OUTPUT;
  let help = false;

  for (const arg of args) {
    if (arg === '--check') {
      if (check) throw new Error('Duplicate --check argument.');
      check = true;
    } else if (arg === '--help' || arg === '-h') {
      help = true;
    } else if (arg.startsWith('--source=')) {
      source = arg.slice('--source='.length);
    } else if (arg.startsWith('--output=')) {
      output = arg.slice('--output='.length);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  if (help && args.length > 1) throw new Error('--help cannot be combined with other arguments.');
  const parsed = {
    check,
    help,
    outputPath: resolveWorkspacePath(output, '--output'),
    sourcePath: resolveWorkspacePath(source, '--source'),
  };
  if (parsed.outputPath === parsed.sourcePath) throw new Error('--output cannot overwrite --source.');
  return parsed;
};

const importSass = async () => {
  try {
    return await import('sass');
  } catch (error) {
    throw new Error('The pinned sass package is required. Run npm ci before building styles.', {
      cause: error,
    });
  }
};

const readPinnedBootstrapPackage = async () => {
  const packagePath = path.join(ROOT, 'node_modules', 'bootstrap', 'package.json');
  assertSafeExistingFile(packagePath, 'Pinned Bootstrap package');
  const packageJson = JSON.parse(await fs.readFile(packagePath, 'utf8'));
  if (packageJson.version !== BOOTSTRAP_VERSION) {
    throw new Error(
      `Bootstrap ${BOOTSTRAP_VERSION} is required; node_modules contains ${packageJson.version || 'an unknown version'}.`
    );
  }
  return packagePath;
};

const buildBootstrapCss = async ({ sourcePath = resolveWorkspacePath(DEFAULT_SOURCE) } = {}) => {
  assertSafeExistingFile(sourcePath, 'Bootstrap Sass entrypoint');
  await readPinnedBootstrapPackage();
  const sass = await importSass();
  const result = await sass.compileAsync(sourcePath, {
    charset: false,
    loadPaths: [path.join(ROOT, 'node_modules')],
    quietDeps: true,
    sourceMap: false,
    style: 'expanded',
  });

  const bootstrapRoot = path.join(ROOT, 'node_modules', 'bootstrap', 'scss');
  const loadedBootstrap = result.loadedUrls.some((url) => {
    if (url.protocol !== 'file:') return false;
    return fileURLToPath(url).startsWith(`${bootstrapRoot}${path.sep}`);
  });
  if (!loadedBootstrap) throw new Error('Selective Sass build did not load the pinned Bootstrap sources.');

  const header =
    `/* Generated by tools/build-bootstrap-site.mjs (${BUILD_VERSION}).\n` +
    `   Source: ${relativeLabel(sourcePath)}; Bootstrap: ${BOOTSTRAP_VERSION}.\n` +
    '   Do not edit directly. */\n';
  return `${header}${result.css.trimEnd()}\n`;
};

const main = async () => {
  const options = parseArgs();
  if (options.help) {
    console.log(usage);
    return;
  }
  const css = await buildBootstrapCss({ sourcePath: options.sourcePath });
  if (options.check) {
    assertSafeExistingFile(options.outputPath, 'Bootstrap CSS output');
    const current = await fs.readFile(options.outputPath, 'utf8');
    if (current !== css) {
      throw new Error(
        `${relativeLabel(options.outputPath)} is stale. Run node tools/build-bootstrap-site.mjs.`
      );
    }
    console.log(`Bootstrap CSS is current: ${relativeLabel(options.outputPath)}.`);
    return;
  }

  assertSafeOutputPath(options.outputPath, 'Bootstrap CSS output');
  atomicWriteFile(options.outputPath, css);
  console.log(`Wrote ${relativeLabel(options.outputPath)} (${Buffer.byteLength(css)} bytes).`);
};

export {
  BOOTSTRAP_VERSION,
  BUILD_VERSION,
  DEFAULT_OUTPUT,
  DEFAULT_SOURCE,
  buildBootstrapCss,
  parseArgs,
};

if (process.argv[1] && path.resolve(process.argv[1]) === THIS_FILE) {
  main().catch((error) => {
    console.error(error.stack || error.message || String(error));
    process.exitCode = 1;
  });
}
